//! 场景唯一标识符定义。

/// 场景的唯一标识符，对应游戏中的每一个 UI 界面。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SceneId {
    /// 大世界界面
    大世界,
    /// 协议终端界面
    协议终端,
    /// 档案库主界面
    档案库主界面,
    /// 档案库子界面（带具体分类）
    档案库子界面(SubSceneKind),
    /// 档案详情页面（查看单份档案内容）
    档案详情页面,
    /// 未知界面（无法识别的界面）
    未知,
}

/// 档案库子界面的具体分类。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SubSceneKind {
    /// 音像存档 - 多媒体（只有这一个子界面）
    音像存档_多媒体,
    /// 见闻辑录 - 纸质记录
    见闻辑录_纸质记录,
    /// 见闻辑录 - 电子档案
    见闻辑录_电子档案,
    /// 见闻辑录 - 藏品
    见闻辑录_藏品,
    /// 中枢档案 - 中枢档案
    中枢档案_中枢档案,
    /// 中枢档案 - 调查报告
    中枢档案_调查报告,
}
